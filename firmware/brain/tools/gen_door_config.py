"""Generate src/door_config.h from door-config/bringup-*.txt (one STM shell line each).
Run from firmware/brain:  python3 tools/gen_door_config.py ../../door-config/bringup-2026-11-20.txt"""
import sys, pathlib
src = pathlib.Path(sys.argv[1])
lines = [l.strip() for l in src.read_text().splitlines() if l.strip() and not l.startswith('#')]
for l in lines:
    w = l.split()[0]
    assert w.startswith('set_') or w == 'profiled_state', f'not a config line: {l}'
out = ['// Generated by tools/gen_door_config.py from ' + str(src.name) + '. Do not edit.',
       '// STM setup lines (no motion), sent after every STM boot. Position is set separately.',
       '#pragma once', 'static const char *const kDoorConfig[] = {']
out += [f'    "{l}",' for l in lines]
out += ['};', f'static const int kDoorConfigN = {len(lines)};', '']
pathlib.Path('src/door_config.h').write_text('\n'.join(out))
print(f'{len(lines)} lines')
