#!/usr/bin/env python3
"""Generate control.kicad_sch from design.py: every symbol placed on one sheet, every pin connected by a
net label at its end (unused pins get a no-connect flag). Run: python3 gen_sch.py
Then check with: kicad-cli sch erc control.kicad_sch"""
import os
import re
import uuid

import design

HERE = os.path.dirname(os.path.abspath(__file__))
KICAD_SYM = "/Applications/KiCad/KiCad.app/Contents/SharedSupport/symbols"
LIBS = {"Espressif": os.path.join(HERE, "lib/Espressif.kicad_sym"), "Control": os.path.join(HERE, "lib/Control.kicad_sym")}
NS = uuid.UUID("6b1d0f4e-6d0c-4c1e-9a77-0c8a2f1e5b10")  # stable uuids: same input, same file


def uid(*parts):
    return str(uuid.uuid5(NS, "/".join(map(str, parts))))


def lib_path(lib):
    return LIBS.get(lib) or os.path.join(KICAD_SYM, lib + ".kicad_sym")


def sexpr_block(text, start):
    depth = 0
    for k in range(start, len(text)):
        if text[k] == "(":
            depth += 1
        elif text[k] == ")":
            depth -= 1
            if depth == 0:
                return text[start:k + 1]
    raise ValueError("unbalanced")


_cache = {}


def symbol_def(lib_id):
    """(block text renamed to lib_id, [(pin number, x, y, angle)]) with `extends` resolved."""
    if lib_id in _cache:
        return _cache[lib_id]
    lib, name = lib_id.split(":")
    text = open(lib_path(lib)).read()
    i = text.find(f'(symbol "{name}"')
    if i < 0:
        raise KeyError(lib_id)
    blk = sexpr_block(text, i)
    ext = re.search(r'\(extends "([^"]+)"\)', blk)
    if ext:  # take the parent's graphics and pins, keep this symbol's properties
        parent = sexpr_block(text, text.find(f'(symbol "{ext.group(1)}"'))
        props = re.findall(r'\(property "[^"]+".*?\n\t\t\)', blk, re.S)
        body = parent[parent.find("\n"):]
        body = re.sub(r'\(property "[^"]+".*?\n\t\t\)', "", body, flags=re.S)
        body = body.replace(f'(symbol "{ext.group(1)}_', f'(symbol "{name}_')
        blk = f'(symbol "{name}"\n\t\t' + "\n\t\t".join(props) + body
    blk = blk.replace(f'(symbol "{name}"', f'(symbol "{lib_id}"', 1)
    pins = [(m.group(4), float(m.group(1)), float(m.group(2)), int(float(m.group(3))))
            for m in re.finditer(r'\(pin \w+ \w+\s*\(at ([-\d.]+) ([-\d.]+) ([-\d.]+)\).*?\(number "([^"]+)"', blk, re.S)]
    _cache[lib_id] = (blk, pins)
    return _cache[lib_id]


def prop(name, value, x, y, hide=False, angle=0):
    h = "\n\t\t\t\t(hide yes)" if hide else ""
    return (f'\t\t(property "{name}" "{value}"\n\t\t\t(at {x:.2f} {y:.2f} {angle})\n\t\t\t(effects\n\t\t\t\t(font (size 1.27 1.27)){h}\n'
            f'\t\t\t)\n\t\t)')


def main():
    parts = design.all_parts()
    root = uid("root")
    used = sorted({p["symbol"] for p in parts.values()} | {"power:PWR_FLAG"})
    out = ['(kicad_sch\n\t(version 20250114)\n\t(generator "wayzn-control-gen")\n\t(generator_version "10.0")',
           f'\t(uuid "{root}")\n\t(paper "A3")',
           '\t(title_block\n\t\t(title "wayzn-afterlife control board (WYP-BC-100 replacement)")\n\t\t(comment 1 "Generated by gen_sch.py from design.py: edit design.py, not this file")\n\t)',
           "\t(lib_symbols"]
    for lid in used:
        out.append("\t\t" + symbol_def(lid)[0].replace("\n", "\n\t"))
    out.append("\t)")

    # Layout: big parts on the left, connectors in the middle, passives in a grid on the right.
    order = [r for r in ["U1", "U2", "U3", "J1", "J2", "J3", "J4", "J5", "D1", "TP1", "TP2", "TP3"] if r in parts]
    order += sorted((r for r in parts if r not in order),
                    key=lambda r: (re.match(r"[A-Z]+", r).group(), int(re.search(r"\d+", r).group())))
    slots = {"U1": (60.96, 88.9), "U2": (60.96, 200.66), "U3": (152.4, 220.98)}
    x, y = 152.4, 50.8
    for ref in order:
        if ref in slots:
            continue
        slots[ref] = (x, y)
        y += 30.48
        if y > 190:
            y, x = 50.8, x + 50.8
    labels = []
    for ref in order:
        p = parts[ref]
        blk, pins = symbol_def(p["symbol"])
        X, Y = slots[ref]
        inst = [f'\t(symbol\n\t\t(lib_id "{p["symbol"]}")\n\t\t(at {X:.2f} {Y:.2f} 0)\n\t\t(unit 1)',
                "\t\t(exclude_from_sim no)\n\t\t(in_bom " + ("no" if p["dnp"] else "yes") + ")\n\t\t(on_board yes)" + ("\n\t\t(dnp yes)" if p["dnp"] else "\n\t\t(dnp no)"),
                f'\t\t(uuid "{uid("sym", ref)}")',
                prop("Reference", ref, X, Y - 3.81), prop("Value", p["value"], X, Y + 3.81),
                prop("Footprint", p["footprint"], X, Y, hide=True), prop("Datasheet", "", X, Y, hide=True),
                prop("Description", p["notes"].replace('"', "'"), X, Y, hide=True),
                prop("LCSC", p["lcsc"], X, Y, hide=True)]
        seen = set()
        for num, px, py, ang in pins:
            if num in seen:
                continue
            seen.add(num)
            inst.append(f'\t\t(pin "{num}"\n\t\t\t(uuid "{uid("pin", ref, num)}")\n\t\t)')
        inst.append(f'\t\t(instances\n\t\t\t(project "control"\n\t\t\t\t(path "/{root}"\n\t\t\t\t\t(reference "{ref}")\n'
                    f'\t\t\t\t\t(unit 1)\n\t\t\t\t)\n\t\t\t)\n\t\t)\n\t)')
        out.append("\n".join(inst))
        for num, px, py, ang in pins:  # stacked pins (several GND with one number) share one point
            cx, cy = round(X + px, 2), round(Y - py, 2)
            if (cx, cy) in labels:
                continue
            labels.append((cx, cy))
            net = p["pins"].get(num, None)
            if net is None:
                out.append(f'\t(no_connect\n\t\t(at {cx:.2f} {cy:.2f})\n\t\t(uuid "{uid("nc", ref, num, cx, cy)}")\n\t)')
                continue
            la = (ang + 180) % 360
            just = {0: "left", 180: "right", 90: "left", 270: "right"}[la]
            out.append(f'\t(label "{net}"\n\t\t(at {cx:.2f} {cy:.2f} {la})\n\t\t(effects\n\t\t\t(font (size 1.0 1.0))\n'
                       f'\t\t\t(justify {just} bottom)\n\t\t)\n\t\t(uuid "{uid("lbl", ref, num, cx, cy)}")\n\t)')
    # PWR_FLAGs: the supply comes in on connectors (passive pins), so mark the rails as driven.
    _, fpins = symbol_def("power:PWR_FLAG")
    for i, net in enumerate([design.V, design.G, design.VM]):
        X, Y = 30.48 + 20.32 * i, 266.7
        ref = f"#FLG0{i + 1}"
        out.append(f'\t(symbol\n\t\t(lib_id "power:PWR_FLAG")\n\t\t(at {X:.2f} {Y:.2f} 0)\n\t\t(unit 1)\n'
                   f'\t\t(exclude_from_sim no)\n\t\t(in_bom yes)\n\t\t(on_board yes)\n\t\t(dnp no)\n\t\t(uuid "{uid("flag", net)}")\n'
                   + prop("Reference", ref, X, Y - 5, hide=True) + "\n" + prop("Value", "PWR_FLAG", X, Y + 3.81) + "\n"
                   + prop("Footprint", "", X, Y, hide=True) + "\n" + prop("Datasheet", "", X, Y, hide=True) + "\n"
                   + f'\t\t(pin "1"\n\t\t\t(uuid "{uid("flagpin", net)}")\n\t\t)\n'
                   + f'\t\t(instances\n\t\t\t(project "control"\n\t\t\t\t(path "/{root}"\n\t\t\t\t\t(reference "{ref}")\n'
                   f'\t\t\t\t\t(unit 1)\n\t\t\t\t)\n\t\t\t)\n\t\t)\n\t)')
        num, px, py, ang = fpins[0]
        cx, cy = X + px, Y - py
        out.append(f'\t(label "{net}"\n\t\t(at {cx:.2f} {cy:.2f} 270)\n\t\t(effects\n\t\t\t(font (size 1.0 1.0))\n'
                   f'\t\t\t(justify right bottom)\n\t\t)\n\t\t(uuid "{uid("flaglbl", net)}")\n\t)')
    out.append(f'\t(sheet_instances\n\t\t(path "/"\n\t\t\t(page "1")\n\t\t)\n\t)\n\t(embedded_fonts no)\n)')
    open(os.path.join(HERE, "control.kicad_sch"), "w").write("\n".join(out) + "\n")
    print("wrote control.kicad_sch:", len(parts), "parts")


if __name__ == "__main__":
    main()
